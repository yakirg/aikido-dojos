CREATE TABLE membership (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practitioner_id BIGINT NOT NULL,
    dojo_id BIGINT NOT NULL,
    start_date DATE,
    end_date DATE,
    CONSTRAINT fk_membership_practitioner FOREIGN KEY (practitioner_id) REFERENCES practitioner (id) ON DELETE CASCADE,
    CONSTRAINT fk_membership_dojo FOREIGN KEY (dojo_id) REFERENCES dojo (id)
);

CREATE INDEX idx_membership_practitioner ON membership (practitioner_id);
CREATE INDEX idx_membership_dojo ON membership (dojo_id);

INSERT INTO membership (practitioner_id, dojo_id, start_date)
SELECT id, dojo_id, start_date FROM practitioner WHERE dojo_id IS NOT NULL;

DROP INDEX idx_practitioner_dojo;
ALTER TABLE practitioner DROP CONSTRAINT fk_practitioner_dojo;
ALTER TABLE practitioner DROP COLUMN dojo_id;
