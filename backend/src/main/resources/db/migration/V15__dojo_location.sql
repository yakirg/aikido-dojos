CREATE TABLE dojo_location (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dojo_id BIGINT NOT NULL,
    address VARCHAR(300),
    city VARCHAR(100),
    state VARCHAR(100),
    postal_code VARCHAR(20),
    country VARCHAR(100) NOT NULL,
    start_date VARCHAR(10),
    end_date VARCHAR(10),
    CONSTRAINT fk_dojo_location_dojo FOREIGN KEY (dojo_id) REFERENCES dojo (id) ON DELETE CASCADE
);

CREATE INDEX idx_dojo_location_dojo ON dojo_location (dojo_id);

-- Each dojo's existing address becomes its first location, starting when the dojo was founded.
INSERT INTO dojo_location (dojo_id, address, city, state, postal_code, country, start_date, end_date)
SELECT id, address, city, state, postal_code, country, founded_date, closed_date FROM dojo;