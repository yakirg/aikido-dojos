CREATE TABLE dojo_leader (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dojo_id BIGINT NOT NULL,
    practitioner_id BIGINT NOT NULL,
    start_date VARCHAR(10),
    end_date VARCHAR(10),
    founder BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_dojo_leader_dojo FOREIGN KEY (dojo_id) REFERENCES dojo (id) ON DELETE CASCADE,
    CONSTRAINT fk_dojo_leader_practitioner FOREIGN KEY (practitioner_id) REFERENCES practitioner (id) ON DELETE CASCADE
);

CREATE INDEX idx_dojo_leader_dojo ON dojo_leader (dojo_id);
CREATE INDEX idx_dojo_leader_practitioner ON dojo_leader (practitioner_id);

-- Founders are the first leaders: they start leading when the dojo was founded.
INSERT INTO dojo_leader (dojo_id, practitioner_id, start_date, founder)
SELECT f.dojo_id, f.practitioner_id, d.founded_date, TRUE
FROM dojo_founder f JOIN dojo d ON d.id = f.dojo_id;

DROP TABLE dojo_founder;
