CREATE TABLE rank_award (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    practitioner_id BIGINT NOT NULL,
    rank_name VARCHAR(50) NOT NULL,
    awarded_date DATE,
    CONSTRAINT fk_rank_award_practitioner FOREIGN KEY (practitioner_id) REFERENCES practitioner (id) ON DELETE CASCADE
);

CREATE INDEX idx_rank_award_practitioner ON rank_award (practitioner_id);

INSERT INTO rank_award (practitioner_id, rank_name, awarded_date)
SELECT id, rank_name, NULL FROM practitioner WHERE rank_name IS NOT NULL;