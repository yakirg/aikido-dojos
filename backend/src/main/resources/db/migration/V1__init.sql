CREATE TABLE dojo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    city VARCHAR(100),
    country VARCHAR(100) NOT NULL,
    address VARCHAR(300),
    website VARCHAR(300),
    founded_year INTEGER
);

CREATE TABLE practitioner (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(200),
    rank_name VARCHAR(50),
    start_date DATE,
    dojo_id BIGINT,
    CONSTRAINT fk_practitioner_dojo FOREIGN KEY (dojo_id) REFERENCES dojo (id)
);

CREATE INDEX idx_practitioner_dojo ON practitioner (dojo_id);
